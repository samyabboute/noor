"use client";

import { useEffect } from "react";
import Lenis from "lenis";

/**
 * Global buttery smooth-scroll — a big perceived-luxury win, GPU-friendly.
 * Disabled entirely under prefers-reduced-motion, and on coarse pointers we
 * keep it gentle so touch flicks still feel native.
 */
export default function SmoothScroll() {
  useEffect(() => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    const lenis = new Lenis({
      duration: 1.1,
      easing: (t) => 1 - Math.pow(1 - t, 3),
      smoothWheel: true,
      touchMultiplier: 1.4,
    });

    let raf = 0;
    const loop = (time: number) => {
      lenis.raf(time);
      raf = requestAnimationFrame(loop);
    };
    raf = requestAnimationFrame(loop);

    return () => {
      cancelAnimationFrame(raf);
      lenis.destroy();
    };
  }, []);

  return null;
}
